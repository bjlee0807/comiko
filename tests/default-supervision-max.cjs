const assert = require('node:assert/strict');
const load = require('./load-ts.cjs');
const { countExamPeriods, applyDefaultMax } = load('lib/default-supervision-max.ts');
const { makeExamFile, readExamFile, copyForNextExam } = load('lib/exam-file.ts');
const { applyTeacherTimetable, NEW_TEACHER } = load('lib/teacher-timetable.ts');
const { applyRoster } = load('lib/teacher-roster.ts');
const s = { id: 's1', date: '2026/9/7(월)', period: '1교시', grade1Subject: '국어', grade2Subject: '영어', grade3Subject: '시험 없음', rooms: '1-1' };
assert.equal(countExamPeriods([s], 2026), 1);
assert.equal(countExamPeriods([s, { ...s, id: 's2', date: '9/7(월)', period: '01' }], 2026), 1);
assert.equal(countExamPeriods([s, { ...s, date: '2026/9/8(화)' }, { ...s, period: '2교시' }], 2026), 3);
assert.equal(countExamPeriods([{ ...s, grade1Subject: '자습', grade2Subject: '시험 없음', grade3Subject: '' }], 2026), 0);
assert.equal(countExamPeriods([{ ...s, date: '' }, { ...s, period: '' }], 2026), 0);
assert.equal(countExamPeriods([], 2026), 0);
const teacher = { id: 't1', name: '테스트교사', subject: '수학', homeroom: '', role: '교과교사', max: 0, unavailable: '', dailyMax: 1 };
const original = [teacher, { ...teacher, id: 't2', autoMax: true }, { ...teacher, id: 't3', max: 2, autoMax: false }];
assert.deepEqual(applyDefaultMax(original, 9).map(t => t.max), [0, 9, 2]);
assert.deepEqual(original.map(t => t.max), [0, 0, 2]);
assert.equal(applyDefaultMax(original, 9)[1].dailyMax, 1);
const data = { name: '2026 시험', teachers: applyDefaultMax(original, 9), sessions: [s], assignments: {}, excludeHomeroom: true };
const saved = readExamFile(makeExamFile(data)).data;
assert.equal(saved.teachers[1].autoMax, true);
assert.equal(saved.teachers[2].autoMax, false);
assert.equal(applyDefaultMax(copyForNextExam(saved, '다음 시험').teachers, 0)[1].max, 0);
const added = applyTeacherTimetable([], { sheet: '시간표', errors: [], rows: [{ name: '새교사', subject: '국어', homeroom: '', taughtClasses: '', row: 5 }] }, [NEW_TEACHER], () => 'new', 9);
assert.equal(added[0].max, 9);
assert.equal(added[0].autoMax, true);
const roster = applyRoster([{ ...teacher, autoMax: true }], [{ name: teacher.name, subject: '수학', homeroom: '', role: '교과교사', max: 2 }], 'merge', () => 'new');
assert.equal(roster[0].autoMax, false);
assert.equal(applyDefaultMax(roster, 9)[0].max, 2);
console.log('PASS: default exam-period counting, concurrent grades, study exclusion, custom limits, timetable import and persistence');
