const assert = require('node:assert/strict');
const fs = require('node:fs');
const { setAllTeacherMax, applyDefaultMax } = require('./load-ts.cjs')('lib/default-supervision-max.ts');
const teachers = [{ id: 't1', max: 0, autoMax: false, dailyMax: 1, unavailable: 's1', allowedDuty: 'assistant' }, { id: 't2', max: 3, autoMax: true, lowLoad: true }];
const before = JSON.stringify(teachers);
const manual = setAllTeacherMax(teachers, 6, false);
assert.deepEqual(manual.map(t => [t.max, t.autoMax]), [[6, false], [6, false]]);
assert.equal(applyDefaultMax(manual, 9)[0].max, 6);
assert.deepEqual(applyDefaultMax(setAllTeacherMax(teachers, 6, true), 9).map(t => t.max), [9, 9]);
assert.deepEqual(setAllTeacherMax(teachers, 0, false).map(t => t.max), [0, 0]);
assert.equal(manual[0].dailyMax, 1);
assert.equal(manual[0].unavailable, 's1');
assert.equal(manual[0].allowedDuty, 'assistant');
assert.equal(manual[1].lowLoad, true);
assert.equal(JSON.stringify(teachers), before);
for (const value of [-1, 1.5, NaN, Infinity, Number.MAX_SAFE_INTEGER + 1]) assert.throws(() => setAllTeacherMax(teachers, value, false));
assert.deepEqual(setAllTeacherMax([], 3, false), []);
const ui = fs.readFileSync('components/bulk-teacher-max.tsx', 'utf8');
assert.ok(ui.includes('!valid || !approved'));
assert.ok(ui.includes('setApproved(false)'));
const page = fs.readFileSync('app/page.tsx', 'utf8');
assert.ok(/<BulkTeacherMax\s+[\s\S]*?teachers=\{teachers\}/.test(page));
assert.ok(page.includes('src="/school-emblem.png"'));
assert.ok(page.includes('<span>시험감독편성</span>'));
assert.equal(fs.readFileSync('public/school-emblem.png').subarray(1, 4).toString(), 'PNG');
console.log('PASS: bulk manual/default limits, zero, invalid input, preserved conditions, confirmation and school branding');
