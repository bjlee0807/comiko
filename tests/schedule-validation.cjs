const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('app/page.tsx', 'utf8');
const helpers = source.slice(source.indexOf('function roomOrder'), source.indexOf('export default function Home'));
const context = vm.createContext({ specialRooms: [], ...require('./load-ts.cjs')('lib/school-rules.ts'), ...require('./load-ts.cjs')('lib/setter-rules.ts'), ...require('./load-ts.cjs')('lib/hallway-supervision.ts') });
vm.runInContext(ts.transpile(fs.readFileSync('lib/session-grades.ts', 'utf8').replace(/export /g, ''), { target: ts.ScriptTarget.ES2022 }), context);
vm.runInContext(ts.transpile(fs.readFileSync('lib/exam-date.ts', 'utf8').replace(/export /g, ''), { target: ts.ScriptTarget.ES2022 }), context);
vm.runInContext(ts.transpile(helpers, { target: ts.ScriptTarget.ES2022 }), context);
const t = { id: 't', name: '검사교사', subject: '국어', homeroom: '2-1', max: 1, unavailable: 's1' };
const s = { id: 's1', date: '4/27', period: '1교시', grade2Subject: '국어', rooms: '2-1' };
let result = context.validateSchedule([t], [s], { 's1::2-1': { chief: 't', assistant: 't' } }, true);
for (const kind of ['중복 배정', '감독 불가', '교과 충돌', '담임 학급', '횟수 초과']) assert.ok(result.some(i => i.kind === kind), kind);
assert.ok(result.every(i => i.target === 'assignment-s1::2-1'));
result = context.validateSchedule([t], [s], {}, false);
assert.equal(result.filter(i => i.kind === '미배정').length, 2);
const study = { ...s, grade2Subject: '자습' };
const free = { ...t, subject: '', homeroom: '', max: 9, unavailable: '' };
assert.equal(context.validateSchedule([free], [study], { 's1::2-1': { chief: 't' } }, true).length, 0);
const other = { ...study, id: 's2', rooms: '2-2' };
result = context.validateSchedule([free], [study, other], { 's1::2-1': { chief: 't' }, 's2::2-2': { chief: 't' } }, false);
assert.equal(result.filter(i => i.kind === '중복 배정').length, 2);
assert.equal(context.validateSchedule([free], [{ ...s, rooms: '' }], {}, false)[0].kind, '설정 확인');
assert.ok(source.includes('id={\'assignment-\' + key}'));
assert.ok(source.includes('onClick={() => goToIssue(issue.target)}'));
console.log('PASS: all validation types, study duty, cross-session duplicates, empty rooms and navigation targets');
